import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const base = process.argv[2] ?? "origin/master";
const moves = JSON.parse(readFileSync(path.join(root, "features/whiteboard/docs/moves.json"), "utf8"));
const before = (file) => execFileSync("git", ["show", `${base}:${file}`], { cwd: root });
const current = (file) => readFileSync(path.join(root, file));
const unchanged = (old, file) => {
  assert.deepEqual(current(file), before(old), `${old} changed while moving to ${file}`);
  console.log(`unchanged: ${file} sha256:${createHash("sha256").update(current(file)).digest("hex")}`);
};
unchanged("contract/schema/whiteboard-v1.json", "features/whiteboard/contract/whiteboard-v1.json");
unchanged("contract/generated/openapi.json", "contract/generated/openapi.json");
for (const [old, file] of Object.entries(moves)) {
  if (file.endsWith(".sql") && file.startsWith("features/whiteboard/api/")) unchanged(old, file);
}

const outputs = [
  ["whiteboard-v1.ts", "sdks/typescript/client/src/generated/whiteboard-v1.ts", "features/whiteboard/sdk/client/src/generated/whiteboard-v1.ts"],
  ["view-limits.ts", "packages/whiteboard/src/collab/view-limits.ts", "features/whiteboard/packages/canvas/src/collab/view-limits.ts"],
  ["whiteboard.ex", "apps/sync/lib/chalk_sync/contract/generated_whiteboard_v1.ex", "features/whiteboard/sync/lib/chalk_sync/contract/generated_whiteboard_v1.ex"],
];
const temporary = mkdtempSync(path.join(tmpdir(), "whiteboard-contract-comparison-"));
const withoutProvenance = (source) => source.toString().replace(/^.*Generated by.*\n/gm, "");
try {
  const retention = path.join(temporary, "retention.ex");
  writeFileSync(retention, before("apps/sync/lib/chalk_sync/retention/sql.ex"));
  execFileSync(
    "elixir",
    [
      "-r",
      retention,
      "-r",
      "features/whiteboard/sync/lib/chalk_sync/whiteboard_v1/sql.ex",
      "-e",
      `
    names = ~w(delete_whiteboard_operation_receipts delete_whiteboard_permissions delete_whiteboard_draw_policies delete_whiteboard_draw_policy_receipts delete_whiteboard_elements delete_whiteboard_scenes)a
    before = Enum.map(names, &apply(ChalkSync.Retention.SQL, &1, []))
    unless before == ChalkSync.WhiteboardV1.SQL.retention_deletions(), do: raise("whiteboard retention SQL changed")
    IO.puts("unchanged: all six whiteboard retention queries, in order")
  `,
    ],
    { cwd: root, stdio: "inherit" },
  );
  const env = {
    ...process.env,
    CODEGEN_WHITEBOARD_TYPESCRIPT_OUTPUT_PATH: path.join(temporary, outputs[0][0]),
    CODEGEN_WHITEBOARD_VIEW_LIMITS_OUTPUT_PATH: path.join(temporary, outputs[1][0]),
    CODEGEN_WHITEBOARD_ELIXIR_OUTPUT_PATH: path.join(temporary, outputs[2][0]),
  };
  for (const emitter of ["whiteboard-typescript", "whiteboard-elixir"]) {
    execFileSync("node", [`features/whiteboard/tools/emitters/${emitter}.mjs`], { cwd: root, env, stdio: "inherit" });
  }
  execFileSync("pnpm", ["exec", "oxfmt", "--write", ...outputs.slice(0, 2).map(([name]) => path.join(temporary, name))], { cwd: root, stdio: "inherit" });
  for (const [name, old, file] of outputs) {
    assert.equal(withoutProvenance(readFileSync(path.join(temporary, name))), withoutProvenance(current(file)), `fresh ${name} differs from checked-in output`);
    assert.equal(withoutProvenance(current(file)), withoutProvenance(before(old)), `${name} differs from the pre-move contract`);
    console.log(`regenerated and unchanged (excluding emitter-path comment): ${file}`);
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
