import { readFile, writeFile } from "node:fs/promises";

const domain = "apps/api/internal/publicinvites/";
const words = (await readFile(`${domain}words.txt`, "utf8")).trim().split("\n");
const source = await readFile(`${domain}code.go`, "utf8");
const count = Number(source.match(/const InviteWordCount = (\d+)/)?.[1]);
if (words.length !== 1024 || new Set(words).size !== 1024 || words.some((word) => !/^[a-z]+$/.test(word)) || ![3, 4].includes(count)) throw new Error("Invalid frozen invite dictionary or word count");
const sql = `create function space_public_invite_words(handle bytea) returns text
language sql immutable strict parallel safe
as $$
    select string_agg(words[1 + ((get_byte(digest, (i * 10) / 8)::bigint * 65536
        + get_byte(digest, (i * 10) / 8 + 1) * 256
        + get_byte(digest, (i * 10) / 8 + 2)) >> (14 - (i * 10) % 8) & 1023)], '-' order by i)
    from (select sha256('chalk/public-invite/words/v1'::bytea || handle) as digest,
        array[${words.map((word) => `'${word}'`).join(",")} ] as words) hashed,
        generate_series(0, ${count - 1}) as i
$$;`;
const migrationPath = "apps/api/db/migrations/20261025150000_space_public_invite_words.sql";
const migration = `-- Generated by scripts/codegen/invite-words.mjs. Dictionary credit: publicinvites/WORDS.md.
-- +goose Up
-- +goose StatementBegin
${sql}
-- +goose StatementEnd

alter table space_public_invites
    add column invite_words text not null generated always as (space_public_invite_words(handle)) stored;
create unique index space_public_invites_invite_words_idx on space_public_invites(invite_words);

-- +goose Down
drop index space_public_invites_invite_words_idx;
alter table space_public_invites drop column invite_words;
drop function space_public_invite_words(bytea);
`;
const ts = `// Generated by scripts/codegen/invite-words.mjs. See apps/api/internal/publicinvites/WORDS.md.
export const INVITE_WORD_COUNT = ${count};
export const INVITE_WORDS = new Set(
  "${words.join(" ")}".split(
    " ",
  ),
);
`;
let schema = await readFile("apps/api/db/schema.sql", "utf8");
schema = schema.replace(/create function space_public_invite_words[\s\S]*?\$\$;\n\n/, "");
schema = schema.replace("create table space_public_invites (", () => `${sql}\n\ncreate table space_public_invites (`);
schema = schema.replace(/^    invite_words .*\n/m, "").replace("    generation bigint not null default 1,", "    invite_words text not null generated always as (space_public_invite_words(handle)) stored,\n    generation bigint not null default 1,");
schema = schema
  .replace(/^create unique index space_public_invites_invite_words_idx .*\n/m, "")
  .replace(
    "create unique index space_public_invites_invite_code_idx on space_public_invites(invite_code);",
    "create unique index space_public_invites_invite_code_idx on space_public_invites(invite_code);\ncreate unique index space_public_invites_invite_words_idx on space_public_invites(invite_words);",
  );
for (const [path, content] of [
  [migrationPath, migration],
  ["sdks/typescript/client/src/public-invites/words.ts", ts],
  ["apps/api/db/schema.sql", schema],
]) {
  if (process.argv.includes("--write")) await writeFile(path, content);
  else if ((await readFile(path, "utf8")) !== content) throw new Error(`Stale invite words: ${path}`);
}
