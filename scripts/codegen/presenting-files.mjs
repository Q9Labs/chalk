import { readFile, writeFile } from "node:fs/promises";

const schema = JSON.parse(await readFile("contract/schema/presenting-files-v1.json", "utf8"));
const { kinds, flags, formats, failures } = schema;
const unique = (values) => new Set(values).size === values.length;
const filled = (values) => Array.isArray(values) && values.length > 0 && values.every((value) => typeof value === "string" && value !== "") && unique(values);
if (!filled(kinds) || !filled(flags) || !Array.isArray(formats) || formats.length === 0 || !Array.isArray(failures) || failures.length === 0) throw new Error("presenting files schema is incomplete");
for (const format of formats) {
  if (typeof format.id !== "string" || typeof format.label !== "string" || !filled(format.extensions) || !filled(format.mimeTypes) || !kinds.includes(format.kind) || !flags.includes(format.flag)) throw new Error(`presenting files schema has an invalid format: ${JSON.stringify(format.id)}`);
  if (format.extensions.some((extension) => extension !== extension.toLowerCase() || extension.startsWith("."))) throw new Error(`presenting format ${format.id} extensions must be lower case without a dot`);
}
for (const [name, values] of [
  ["format id", formats.map((format) => format.id)],
  ["extension", formats.flatMap((format) => format.extensions)],
  ["MIME type", formats.flatMap((format) => format.mimeTypes)],
  ["failure code", failures.map((failure) => failure.code)],
]) {
  if (!unique(values)) throw new Error(`presenting files schema repeats a ${name}`);
}
if (failures.some((failure) => typeof failure.message !== "string" || failure.message === "")) throw new Error("presenting failure reasons need a message");

const header = "Generated by scripts/codegen/presenting-files.mjs from contract/schema/presenting-files-v1.json. Do not edit.";
const upper = (value) => value[0].toUpperCase() + value.slice(1);
const goList = (values) => `[]string{${values.map((value) => JSON.stringify(value)).join(", ")}}`;
const go = `// ${header}

package presenting

type FormatFlag string

const (
${flags.map((flag) => `\t${`FormatFlag${upper(flag)}`.padEnd(Math.max(...flags.map((name) => name.length)) + 10)} FormatFlag = ${JSON.stringify(flag)}`).join("\n")}
)

type Format struct {
	ID         string
	Label      string
	Kind       string
	Flag       FormatFlag
	Extensions []string
	MIMETypes  []string
}

var Formats = []Format{
${formats.map((format) => `\t{ID: ${JSON.stringify(format.id)}, Label: ${JSON.stringify(format.label)}, Kind: ${JSON.stringify(format.kind)}, Flag: FormatFlag${upper(format.flag)}, Extensions: ${goList(format.extensions)}, MIMETypes: ${goList(format.mimeTypes)}},`).join("\n")}
}

type FailureReason struct {
	Code    string
	Message string
}

var FailureReasons = []FailureReason{
${failures.map((failure) => `\t{Code: ${JSON.stringify(failure.code)}, Message: ${JSON.stringify(failure.message)}},`).join("\n")}
}
`;

const tsUnion = (values) => values.map((value) => JSON.stringify(value)).join(" | ");
const ts = `// ${header}

export type PresentingFormatKind = ${tsUnion(kinds)};
export type PresentingFormatFlag = ${tsUnion(flags)};

export const PRESENTING_FORMATS = [
${formats.map((format) => `  { id: ${JSON.stringify(format.id)}, label: ${JSON.stringify(format.label)}, kind: ${JSON.stringify(format.kind)}, flag: ${JSON.stringify(format.flag)}, extensions: [${format.extensions.map((value) => JSON.stringify(value)).join(", ")}], mimeTypes: [${format.mimeTypes.map((value) => JSON.stringify(value)).join(", ")}] },`).join("\n")}
] as const;

export type PresentingFormatId = (typeof PRESENTING_FORMATS)[number]["id"];

export const PRESENTING_FAILURE_REASONS = [
${failures.map((failure) => `  { code: ${JSON.stringify(failure.code)}, message: ${JSON.stringify(failure.message)} },`).join("\n")}
] as const;

export type PresentingFailureCode = (typeof PRESENTING_FAILURE_REASONS)[number]["code"];
`;
for (const [path, content] of [
  ["apps/api/internal/presenting/files.gen.go", go],
  ["sdks/typescript/client/src/presenting/files.gen.ts", ts],
]) {
  if (process.argv.includes("--write")) await writeFile(path, content);
  else if ((await readFile(path, "utf8").catch(() => "")) !== content) throw new Error(`Stale presenting files: ${path}`);
}
