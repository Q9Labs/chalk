import { readFile, writeFile } from "node:fs/promises";

const source = "contract/schema/recording-render-v1.json";
const target = "apps/recording-renderer/src/generated/render-contract.ts";
const { frameRenderRequest, composeResult, videoEncoders, decodedMedia } = JSON.parse(await readFile(source, "utf8"));

const tuple = (values) => `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;

const output = `// Generated by scripts/codegen/recording-render-contract.mjs from ${source}.
export const FRAME_RENDER_REQUEST_VERSION = ${JSON.stringify(frameRenderRequest.version)};
export const MAXIMUM_RENDER_WIDTH = ${frameRenderRequest.maxWidth};
export const MAXIMUM_RENDER_HEIGHT = ${frameRenderRequest.maxHeight};
export const MAXIMUM_RENDER_FPS = ${frameRenderRequest.maxFps};
export const MAXIMUM_RECORDING_DURATION_MS = ${frameRenderRequest.maxDurationMs};

export const COMPOSE_RESULT_VERSION = ${JSON.stringify(composeResult.version)};

export const VIDEO_ENCODERS = ${tuple(videoEncoders)} as const;
export type VideoEncoder = (typeof VIDEO_ENCODERS)[number];

export const DECODED_MEDIA_SCHEMA_VERSION = ${JSON.stringify(decodedMedia.version)};
export const DECODED_AUDIO_SAMPLE_RATE_HZ = ${decodedMedia.audioSampleRateHz};
export const DECODED_MICROPHONE_CHANNELS = ${decodedMedia.microphoneChannels};
export const DECODED_MIX_CHANNELS = ${decodedMedia.mixChannels};
export const DECODED_DISCONTINUITY_REASONS = ${tuple(decodedMedia.discontinuityReasons)} as const;
export type DecodedDiscontinuityReason = (typeof DECODED_DISCONTINUITY_REASONS)[number];
`;

if (process.argv.includes("--write")) await writeFile(target, output);
else if ((await readFile(target, "utf8").catch(() => "")) !== output) throw new Error(`Stale recording render contract: ${target}`);
