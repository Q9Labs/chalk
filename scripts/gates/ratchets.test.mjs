import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import { rises } from "./ratchets.mjs";

const baseline = { files: { "a.mjs": 400 }, copies: { "copy.x": 3 } };

test("a file that grew, a new long file and a higher count are all reported", () => {
  const messages = rises(baseline, { files: { "a.mjs": 401, "b.mjs": 301 }, copies: { "copy.x": 4 } });
  assert.equal(messages.length, 3);
  assert.match(messages[0], /a\.mjs grew from 400 to 401/);
  assert.match(messages[1], /b\.mjs has 301 lines/);
  assert.match(messages[2], /copy\.x rose from 3 to 4/);
});

test("equal or lower numbers pass", () => {
  assert.deepEqual(rises(baseline, { files: { "a.mjs": 400 }, copies: { "copy.x": 2 } }), []);
});

test("merge groups ignore baseline drift but reject new growth; --write still checks the whole tree", (t) => {
  const cwd = mkdtempSync(join(tmpdir(), "chalk-ratchets-"));
  t.after(() => rmSync(cwd, { recursive: true, force: true }));
  const git = (...args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  const write = (file, contents) => writeFileSync(join(cwd, file), contents);
  const run = (event, ...args) => spawnSync(process.execPath, ["scripts/gates/ratchets.mjs", ...args], { cwd, env: { ...process.env, ...event }, encoding: "utf8" });
  for (const file of ["scripts/gates/ratchets.mjs", "scripts/gates/ratchet-scope.mjs", "scripts/lib/git.mjs", "scripts/lib/repository.mjs"]) {
    mkdirSync(join(cwd, dirname(file)), { recursive: true });
    copyFileSync(new URL(`../../${file}`, import.meta.url), join(cwd, file));
  }
  git("init", "-b", "master");
  git("config", "user.name", "Test");
  git("config", "user.email", "test@example.com");
  git("config", "commit.gpgsign", "false");
  write("package.json", '{"packageManager":"pnpm@12"}');
  write("scripts/gates/ratchets.json", JSON.stringify({ files: { "base.ex": 300 }, copies: { "copy.port_8443": 0 } }));
  write("base.ex", "# base\n".repeat(310) + "# 8443\n");
  git("add", ".");
  git("commit", "-m", "Master grows ahead of the baseline");
  const baseSha = git("rev-parse", "HEAD");
  git("update-ref", "refs/remotes/origin/master", baseSha);
  git("switch", "-c", "queue");
  write("generated_whiteboard_v1.ex", "# code\n".repeat(500));
  write("compiled.ex", "# Generated by the compiler\n" + "# code\n".repeat(500));
  write("feature.ex", "# work\n");
  git("add", ".");
  git("commit", "-m", "Merge group's unrelated changes");

  const mergeGroup = { GITHUB_EVENT_NAME: "merge_group", GATE_BASE_REF: "" };
  write("event.json", JSON.stringify({ merge_group: { base_sha: baseSha } }));
  mergeGroup.GITHUB_EVENT_PATH = join(cwd, "event.json");
  const scoped = run(mergeGroup);
  assert.equal(scoped.status, 0, scoped.stderr);
  const pr = { GITHUB_EVENT_NAME: "pull_request", GITHUB_BASE_REF: "master", GATE_BASE_REF: "" };
  assert.equal(run(pr).status, 0);
  const full = run(mergeGroup, "--write");
  assert.equal(full.status, 1, full.stderr);
  assert.match(full.stderr, /base\.ex/);
  assert.doesNotMatch(full.stderr, /compiled\.ex|generated_whiteboard_v1\.ex/);

  write("base.ex", "# base\n".repeat(311) + "# 8443\n");
  write("feature.ex", "# work\n".repeat(300) + "# 8443\n");
  const grew = run({}, "--base", baseSha);
  assert.equal(grew.status, 1, grew.stderr);
  assert.match(grew.stderr, /base\.ex grew from 311 to 312/);
  assert.match(grew.stderr, /feature\.ex has 301 lines/);
  assert.match(grew.stderr, /copy\.port_8443 rose from 1 to 2/);
});
