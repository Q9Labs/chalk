import { strict as assert } from "node:assert";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { createDashboardProofFixture } from "./browser-fixture.mjs";

const fixture = await createDashboardProofFixture();
const { context, origin, repository, cleanup } = fixture;
const output = resolve(repository, "artifacts/transcript-language");
await mkdir(output, { recursive: true });
const page = await context.newPage();
const language = page.getByRole("combobox", { name: "Transcript language", exact: true });
const save = page.getByRole("button", { name: "Save transcript language", exact: true });
try {
  await page.goto(`${origin}/dashboard/developer`);
  await language.waitFor();
  assert.equal(await language.inputValue(), "auto");
  await language.selectOption("ur");
  await save.click();
  await page.getByText("Transcript language saved", { exact: true }).waitFor();
  await page.reload();
  await language.waitFor();
  assert.equal(await language.inputValue(), "ur");
  await page.screenshot({ path: resolve(output, "tenant-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, "tenant-phone.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto(`${origin}/dashboard`);
  const created = page.waitForResponse((response) => response.url().endsWith("/dashboard-api/home") && response.request().method() === "POST" && response.status() === 200);
  await page.getByRole("button", { name: "Start a call", exact: true }).click();
  const response = await created;
  const data = await response.json();
  const spaceId = data.call.id;
  await page.goto(`${origin}/dashboard/call/${spaceId}`);
  await language.waitFor();
  assert.equal(await language.inputValue(), "inherit");
  await language.selectOption("ar");
  await save.click();
  await page.getByText("Transcript language saved", { exact: true }).waitFor();
  await page.reload();
  await language.waitFor();
  assert.equal(await language.inputValue(), "ar");
  await page.screenshot({ path: resolve(output, "space-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, "space-phone.png"), fullPage: true });
  await language.selectOption("auto");
  await save.click();
  await page.getByText("Transcript language saved", { exact: true }).waitFor();
  await page.reload();
  assert.equal(await language.inputValue(), "auto");
  await language.selectOption("inherit");
  await save.click();
  await page.getByText("Transcript language saved", { exact: true }).waitFor();
  await page.reload();
  assert.equal(await language.inputValue(), "inherit");
  console.log("PASS account/Space transcript languages persist; explicit auto and inheritance remain distinct");
} finally {
  await cleanup();
}
