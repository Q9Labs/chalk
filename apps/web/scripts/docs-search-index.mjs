// Builds the docs search section index from the MDX headings. `--write` updates it; without it, the script fails when it is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(web, "src/docs/content");
const outFile = path.join(web, "src/docs/search-index.generated.ts");
const EXCERPT_MAX = 140;

const plain = (markdown) =>
  markdown
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/`|\*\*/g, "")
    .replace(/\s+/g, " ")
    .trim();

// Matches github-slugger, which rehype-slug uses for heading ids.
const slugify = (text, seen) => {
  const base = text
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");
  const count = seen.get(base) ?? 0;
  seen.set(base, count + 1);
  return count ? `${base}-${count}` : base;
};

const excerptOf = (blocks) => {
  const paragraph = blocks.find((block) => !/^(```|\||<|>)/.test(block));
  if (!paragraph) return "";
  const text = plain(paragraph.replace(/^([-*]|\d+\.) /, "").split("\n")[0]);
  const sentence = text.match(/^.+?[.!?](?=\s|$)/)?.[0] ?? text;
  if (sentence.length <= EXCERPT_MAX) return sentence;
  return `${sentence.slice(0, EXCERPT_MAX).replace(/\s+\S*$/, "")}…`;
};

const sections = [];
for (const file of readdirSync(contentDir)
  .filter((name) => name.endsWith(".mdx"))
  .sort()) {
  const stem = file.replace(/\.mdx$/, "");
  const slug = stem === "why-chalk" ? "" : stem;
  const source = readFileSync(path.join(contentDir, file), "utf8").replace(/^```[\s\S]*?^```$/gm, (fence) => fence.replace(/\n/g, "\u0000"));
  const seen = new Map();
  for (const part of source.split(/^(?=#{2,3} )/m)) {
    const heading = part.match(/^(#{2,3}) (.+)\n/);
    if (!heading) continue;
    const blocks = part
      .slice(heading[0].length)
      .split(/\n\s*\n/)
      .map((block) => block.trim())
      .filter(Boolean);
    const text = plain(heading[2]);
    sections.push({ slug, heading: text, anchor: slugify(text, seen), excerpt: excerptOf(blocks) });
  }
}

const output = `// Generated by apps/web/scripts/docs-search-index.mjs from the docs MDX headings. Run \`pnpm run regen\` after editing docs content.
export type DocsSection = { readonly slug: string; readonly heading: string; readonly anchor: string; readonly excerpt: string };

export const DOCS_SECTIONS: readonly DocsSection[] = [
${sections.map(({ slug, heading, anchor, excerpt }) => `  { slug: ${JSON.stringify(slug)}, heading: ${JSON.stringify(heading)}, anchor: ${JSON.stringify(anchor)}, excerpt: ${JSON.stringify(excerpt)} },`).join("\n")}
];
`;

if (process.argv.includes("--write")) {
  writeFileSync(outFile, output);
} else if (readFileSync(outFile, "utf8") !== output) {
  console.error(`${path.relative(process.cwd(), outFile)} is stale. Run: node apps/web/scripts/docs-search-index.mjs --write`);
  process.exitCode = 1;
}
