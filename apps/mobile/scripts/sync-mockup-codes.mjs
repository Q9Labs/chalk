#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const mockup = process.argv[2];
if (!mockup) throw new Error("Usage: node sync-mockup-codes.mjs /absolute/mobile-mockup.html");
const source = await readFile(mockup, "utf8");
const table = source.slice(source.indexOf("const BAR="), source.indexOf("function buildBar"));
if (!table) throw new Error("Cannot find the mockup scenario table");
const codes = [...new Set([...table.matchAll(/'([A-Z][0-9]+)'/g)].map((match) => match[1]))];
if (!codes.includes("D1") || !codes.includes("T6")) throw new Error("Incomplete mockup scenario table");
const checksum = createHash("sha256").update(table).digest("hex");
await writeFile(
  new URL("../src/dev-states/codes.ts", import.meta.url),
  `// Scenario table SHA-256: ${checksum}\n// Generated by scripts/sync-mockup-codes.mjs from the approved scratch mockup.\nexport const SCENARIO_CODES = ${JSON.stringify(codes)} as const;\nexport type ScenarioCode = (typeof SCENARIO_CODES)[number];\nexport function isScenarioCode(value: string): value is ScenarioCode { return SCENARIO_CODES.some(code => code === value); }\nexport function parseCodes(value: string): ScenarioCode[] {\n const codes = value.split(",").filter(Boolean);\n return codes.map(code => { if (!isScenarioCode(code)) throw new Error(\`Unknown mockup code: \${code}\`); return code; });\n}\n`,
);
console.log(`Generated ${codes.length} mockup codes (${checksum})`);
