import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { renderAttribute, wrapElixirSource } from "./elixir-layout.mjs";

const schema = JSON.parse(await readFile(new URL("../../../../contract/schema/screen-annotation-v1.json", import.meta.url), "utf8"));
const metadata = schema["x-chalk"];
const typePath = process.env.CODEGEN_SCREEN_ANNOTATION_TYPESCRIPT_OUTPUT_PATH;
const elixirPath = process.env.CODEGEN_SCREEN_ANNOTATION_ELIXIR_OUTPUT_PATH;

if (!typePath || !elixirPath) {
  throw new Error("Run the screen annotation emitter through scripts/codegen/sdk.mjs.");
}

const schemas = JSON.parse(JSON.stringify(schema.$defs).replaceAll("#/$defs/", "#/components/schemas/"));
const declarations = await openapiTS(
  {
    openapi: "3.1.0",
    info: { title: schema.title, version: String(metadata.negotiation.version) },
    paths: {},
    components: { schemas },
  },
  { immutable: true, silent: true },
);

const banner = "Generated by tools/contract-fixture-proof/src/emitters/screen-annotation.mjs. Do not edit.";
const typescript = `// ${banner}
${astToString(declarations)}
export const screenAnnotationV1 = ${JSON.stringify(metadata, null, 2)} as const;
export const screenAnnotationDefinitions = ${JSON.stringify(schema.$defs, null, 2)} as const;
`;
const elixir = wrapElixirSource(`# ${banner}
defmodule ChalkSync.Contract.GeneratedScreenAnnotationV1 do
  @moduledoc false

${renderAttribute("metadata", metadata).join("\n")}
${renderAttribute("definitions", schema.$defs).join("\n")}
  def negotiation, do: @metadata["negotiation"]
  def limits, do: @metadata["limits"]
  def definitions, do: @definitions
end
`);

await Promise.all([mkdir(dirname(typePath), { recursive: true }), mkdir(dirname(elixirPath), { recursive: true })]);
await Promise.all([writeFile(typePath, typescript), writeFile(elixirPath, elixir)]);
