type FixtureClock = {
  readonly now: () => number;
  readonly setTimeout: (callback: () => void, milliseconds: number) => unknown;
  readonly clearTimeout: (handle: unknown) => void;
};

type FixtureMediaDevices = {
  readonly getUserMedia: (constraints: MediaStreamConstraints) => Promise<MediaStream>;
  readonly getDisplayMedia: (constraints: DisplayMediaStreamOptions) => Promise<MediaStream>;
};

const tracks = new Set<MediaStreamTrack>();
const sockets = new Set<WebSocket>();
const peers = new Set<RTCPeerConnection>();
const timers = new Set<unknown>();
const audioContexts = new WeakMap<MediaStreamTrack, AudioContext>();

// Browser events cannot be generated by stopping capture in Playwright itself.
// Change the observable source state as well as dispatching the OS event.
export function interruptMicrophone(kind: "mute" | "ended"): void {
  const microphoneTracks = [...tracks].filter((track) => track.kind === "audio" && track.readyState === "live");
  if (!microphoneTracks.length) throw new Error("No live microphone to interrupt");
  for (const track of microphoneTracks) {
    if (kind === "ended") track.stop();
    else {
      track.enabled = false;
      Object.defineProperty(track, "muted", { configurable: true, value: true });
    }
    track.dispatchEvent(new Event(kind));
  }
}

export const fixtureClock: FixtureClock = {
  now: () => Date.now(),
  setTimeout: (callback, milliseconds) => {
    let handle: ReturnType<typeof setTimeout>;
    handle = setTimeout(() => {
      timers.delete(handle);
      callback();
    }, milliseconds);
    timers.add(handle);
    return handle;
  },
  clearTimeout: (handle) => {
    clearTimeout(handle as ReturnType<typeof setTimeout>);
    timers.delete(handle);
  },
};

export const fixtureMediaDevices: FixtureMediaDevices = {
  getUserMedia: async (constraints) => {
    const mediaTracks: MediaStreamTrack[] = [];
    if (constraints.audio) mediaTracks.push(createAudioTrack());
    if (constraints.video) mediaTracks.push(createVideoTrack("camera"));
    return new MediaStream(mediaTracks);
  },
  getDisplayMedia: async () => new MediaStream([createVideoTrack("screen")]),
};

export function registerSocket(socket: WebSocket): WebSocket {
  sockets.add(socket);
  socket.addEventListener("close", () => sockets.delete(socket), { once: true });
  return socket;
}

export function registerPeer(peer: RTCPeerConnection): RTCPeerConnection {
  peers.add(peer);
  return peer;
}

export function releasePeer(peer: RTCPeerConnection): void {
  peer.close();
  peers.delete(peer);
}

export function releaseTrack(track: MediaStreamTrack): void {
  track.stop();
}

export function resourceCounts() {
  return {
    tracks: [...tracks].filter((track) => track.readyState === "live").length,
    sockets: [...sockets].filter((socket) => socket.readyState === WebSocket.CONNECTING || socket.readyState === WebSocket.OPEN).length,
    peers: [...peers].filter((peer) => peer.connectionState !== "closed").length,
    timers: timers.size,
  };
}

export async function peerStates() {
  return Promise.all(
    [...peers].map(async (peer) => {
      const audio: { type: string; packetsSent?: number; packetsReceived?: number; audioLevel?: number }[] = [];
      (await peer.getStats()).forEach((row) => {
        if (row.kind === "audio" && ["outbound-rtp", "inbound-rtp", "media-source"].includes(row.type)) audio.push({ type: row.type, packetsSent: row.packetsSent, packetsReceived: row.packetsReceived, audioLevel: row.audioLevel });
      });
      return {
        connection: peer.connectionState,
        ice: peer.iceConnectionState,
        signaling: peer.signalingState,
        transceivers: peer.getTransceivers().map((transceiver) => ({
          mid: transceiver.mid,
          direction: transceiver.currentDirection,
          sender: transceiver.sender.track ? { kind: transceiver.sender.track.kind, enabled: transceiver.sender.track.enabled, muted: transceiver.sender.track.muted, context: audioContexts.get(transceiver.sender.track)?.state } : null,
          receiver: transceiver.receiver.track.kind,
          muted: transceiver.receiver.track.muted,
        })),
        audio,
      };
    }),
  );
}

function createVideoTrack(label: string): MediaStreamTrack {
  const canvas = document.createElement("canvas");
  canvas.width = 64;
  canvas.height = 64;
  const context = canvas.getContext("2d");
  if (!context) throw new TypeError("Canvas capture is unavailable");
  context.fillStyle = label === "screen" ? "#ef4444" : "#22c55e";
  context.fillRect(0, 0, canvas.width, canvas.height);
  let frame = 0;
  const timer = setInterval(() => {
    context.fillStyle = `hsl(${(frame++ * 17) % 360} 70% 50%)`;
    context.fillRect(0, 0, canvas.width, canvas.height);
  }, 100);
  const track = canvas.captureStream(5).getVideoTracks()[0];
  if (!track) throw new TypeError("Canvas capture did not return a video track");
  const stop = track.stop.bind(track);
  track.stop = () => {
    clearInterval(timer);
    stop();
  };
  tracks.add(track);
  return track;
}

function createAudioTrack(): MediaStreamTrack {
  const context = new AudioContext();
  const oscillator = context.createOscillator();
  const destination = context.createMediaStreamDestination();
  oscillator.connect(destination);
  oscillator.start();
  void context.resume();
  const track = destination.stream.getAudioTracks()[0];
  if (!track) throw new TypeError("Audio capture did not return a track");
  audioContexts.set(track, context);
  const stop = track.stop.bind(track);
  let released = false;
  track.stop = () => {
    if (released) return;
    released = true;
    stop();
    oscillator.stop();
    void context.close();
  };
  tracks.add(track);
  return track;
}
